def _ensure_dir():
    """确保知识库目录存在"""
    KB_DIR.mkdir(parents=True, exist_ok=True)


def _load_custom():
    """加载用户自定义知识条目"""
    if KB_FILE.exists():
        try:
            return json.loads(KB_FILE.read_text(encoding="utf-8"))
        except Exception:
            pass
    return []


def _save_custom(entries):
    """保存用户自定义知识条目"""
    _ensure_dir()
    KB_FILE.write_text(json.dumps(entries, ensure_ascii=False, indent=2), encoding="utf-8")


def get_all():
    """获取全部知识条目（内置 + 自定义）"""
    return BUILTIN_KNOWLEDGE + _load_custom()


def search(query, limit=5):
    """搜索知识库（关键词匹配）
    
    Args:
        query: 搜索关键词
        limit: 返回条数
    
    Returns:
        list: 匹配的知识条目
    """
    if not query:
        return []
    q = query.strip().lower()
    results = []
    for entry in get_all():
        score = 0
        title = entry.get("title", "").lower()
        content = entry.get("content", "").lower()
        keywords = [k.lower() for k in entry.get("keywords", [])]
        
        # 标题完全匹配
        if q == title:
            score += 10
        # 标题包含
        elif q in title:
            score += 5
        # 关键词匹配
        for kw in keywords:
            if q in kw or kw in q:
                score += 3
        # 内容包含
        if q in content:
            score += 2
        
        if score > 0:
            results.append((score, entry))
    
    results.sort(key=lambda x: -x[0])
    return [e for _, e in results[:limit]]


def get_categories():
    """获取所有分类"""
    cats = []
    seen = set()
    for entry in get_all():
        cat = entry.get("category", "")
        if cat and cat not in seen:
            cats.append(cat)
            seen.add(cat)
    return cats


def get_by_category(category):
    """按分类获取知识条目"""
    return [e for e in get_all() if e.get("category") == category]


def add_custom(title, content, category="自定义", keywords=None):
    """添加用户自定义知识条目
    
    Args:
        title: 标题
        content: 内容
        category: 分类
        keywords: 关键词列表
    
    Returns:
        dict: 新条目
    """
    entries = _load_custom()
    entry = {
        "id": f"custom_{len(entries)+1:03d}",
        "category": category,
        "title": title,
        "content": content,
        "keywords": keywords or [title],
    }
    entries.append(entry)
    _save_custom(entries)
    return entry


def get_context_for_llm(query, limit=3):
    """获取供 LLM 参考的知识上下文
    
    Args:
        query: 用户查询
        limit: 返回条数
    
    Returns:
        str: 格式化的知识上下文
    """
    results = search(query, limit=limit)
    if not results:
        return ""
    lines = ["以下是财务知识库中的相关信息，可作为回答参考：", ""]
    for entry in results:
        lines.append(f"【{entry['category']}】{entry['title']}")
        lines.append(entry["content"])
        lines.append("")
    return "\n".join(lines)
